/**
 * AADALA design — token block sync ONLY (no other file touched).
 * Mirrors scripts/unify-design.mjs syncTokens() so `npm run design:check` stays green.
 * Usage: node scripts/sync-design-tokens.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const tokens = JSON.parse(fs.readFileSync(path.join(ROOT, "design/tokens.json"), "utf8"));
const P = tokens.prefix;
const GLOBALS = "app/globals.css";
const START = `/* @design-tokens:start (generated by scripts/unify-design.mjs — edit design/tokens.json) */`;
const END = "/* @design-tokens:end */";

function tokenBlock() {
  const L = [], D = [], T = [];
  for (const [n, v] of Object.entries(tokens.colors)) {
    L.push(`  --${P}-${n}: ${v.light.toUpperCase()};`);
    if (v.dark) D.push(`  --${P}-${n}: ${v.dark.toUpperCase()};`);
    T.push(`  --color-${n}: var(--${P}-${n});`);
  }
  for (const [n, v] of Object.entries(tokens.fonts)) T.push(`  --font-${n}: ${v};`);
  return `${START}\n:root {\n${L.join("\n")}\n}\n\n[data-theme="dark"] {\n${D.join("\n")}\n}\n\n@theme inline {\n${T.join("\n")}\n}\n${END}`;
}

const file = path.join(ROOT, GLOBALS);
let s = fs.readFileSync(file, "utf8");
const block = tokenBlock();

if (!s.includes(START) || !s.includes(END)) {
  console.error("ERROR: token markers not found in", GLOBALS);
  process.exit(1);
}

const rx = new RegExp(
  START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[\\s\\S]*?" + END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
);
const next = s.replace(rx, () => block);

if (next === s) {
  console.log("Token block already in sync — no change.");
} else {
  fs.writeFileSync(file, next);
  console.log("Token block regenerated from design/tokens.json in", GLOBALS);
  console.log(`  colors: ${Object.keys(tokens.colors).length} · dark: ${Object.values(tokens.colors).filter(v => v.dark).length}`);
}
