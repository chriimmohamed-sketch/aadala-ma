#!/usr/bin/env node
/**
 * AADALA design unifier — zero dependencies.
 *
 *   node scripts/unify-design.mjs            audit only (writes design/report.md)
 *   node scripts/unify-design.mjs --fix      apply safe fixes
 *   node scripts/unify-design.mjs --fix --near   also snap near-miss colors (RGB distance <= 18) to tokens
 *   node scripts/unify-design.mjs --check    CI mode: exit 1 if auto-fixable drift remains (add --strict to also fail on off-palette colors)
 *   node scripts/unify-design.mjs --legacy   (with --fix) also link the legacy HTML pages to the bridge CSS
 *
 * What it does:
 *  1. Generates the token block in app/globals.css (:root, dark theme, @theme) from design/tokens.json.
 *  2. Replaces hard-coded hex colors that exactly match a token with var(--aadala-*).
 *  3. Rewrites off-palette Tailwind utilities (amber/slate/red...) to design-system utilities.
 *  4. Reports colors that match no token, with the nearest token as a suggestion (never guessed silently).
 *  5. Generates assets/css/legacy-bridge.css so the old static pages use the same palette.
 * Files using <canvas> (getContext) are never rewritten, because canvas cannot resolve CSS variables.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const args = new Set(process.argv.slice(2));
const STRICT = args.has("--strict");
const FIX = args.has("--fix"), NEAR = args.has("--near"), CHECK = args.has("--check"), LEGACY = args.has("--legacy");
const tokens = JSON.parse(fs.readFileSync(path.join(ROOT, "design/tokens.json"), "utf8"));
const P = tokens.prefix;
const GLOBALS = "app/globals.css";
const START = "/* @design-tokens:start (generated by scripts/unify-design.mjs — edit design/tokens.json) */";
const END = "/* @design-tokens:end */";

// ---------- helpers ----------
const norm = (h) => { h = h.toLowerCase(); return h.length === 4 ? "#" + [...h.slice(1)].map((c) => c + c).join("") : h; };
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const dist = (a, b) => Math.hypot(...a.map((v, i) => v - b[i]));
const palette = Object.entries(tokens.colors).map(([name, v]) => ({ name, hex: norm(v.light), rgb: rgb(norm(v.light)) }));
const byHex = new Map(palette.map((p) => [p.hex, p.name]));
const nearest = (hex) => palette.map((p) => ({ ...p, d: dist(rgb(hex), p.rgb) })).sort((a, b) => a.d - b.d)[0];

const SKIP_DIRS = new Set(["node_modules", ".next", ".open-next", ".git", "public", "worker", "supabase", ".wrangler"]);
function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(e.name) || e.name.startsWith("AADALA.MA")) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}
const rel = (p) => path.relative(ROOT, p).split(path.sep).join("/");
const files = walk(ROOT).filter((f) => /\.(tsx|css|html)$/.test(f));

// ---------- 1. token block ----------
function tokenBlock() {
  const L = [], D = [], T = [];
  for (const [n, v] of Object.entries(tokens.colors)) {
    L.push(`  --${P}-${n}: ${v.light.toUpperCase()};`);
    if (v.dark) D.push(`  --${P}-${n}: ${v.dark.toUpperCase()};`);
    T.push(`  --color-${n}: var(--${P}-${n});`);
  }
  for (const [n, v] of Object.entries(tokens.fonts)) T.push(`  --font-${n}: ${v};`);
  return `${START}\n:root {\n${L.join("\n")}\n}\n\n[data-theme="dark"] {\n${D.join("\n")}\n}\n\n@theme inline {\n${T.join("\n")}\n}\n${END}`;
}
function syncTokens() {
  const f = path.join(ROOT, GLOBALS);
  let s = fs.readFileSync(f, "utf8");
  const block = tokenBlock();
  if (s.includes(START)) {
    const next = s.replace(new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[\\s\\S]*?" + END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")), () => block);
    return { file: GLOBALS, before: s, after: next };
  }
  // first run: replace the three hand-written blocks with one generated block
  const rx = [/:root\s*\{[^}]*\}\s*/, /\[data-theme="dark"\]\s*\{[^}]*\}\s*/, /@theme inline\s*\{[^}]*\}\s*/];
  let first = -1, next = s;
  for (const r of rx) { const m = next.match(r); if (m) { if (first < 0) first = m.index; next = next.replace(r, ""); } }
  if (first < 0) first = next.indexOf("@import") >= 0 ? next.indexOf("\n", next.indexOf("@import")) + 1 : 0;
  next = next.slice(0, first) + "\n" + block + "\n\n" + next.slice(first);
  return { file: GLOBALS, before: s, after: next };
}

// ---------- 2-4. scan ----------
const HEX = /(?<![\w&/-])(?<!href=["'])(?<!to=["'])(?<!id=["'])#([0-9a-fA-F]{8}|[0-9a-fA-F]{6})\b/g;
const HEX3 = /(?<![\w&/-])#([0-9a-fA-F]{3})\b/g;
const report = { legacy: [], exact: [], near: [], off: [], tw: [], skipped: [], inline: [] };
const changes = new Map();

function scan(file) {
  const r = rel(file);
  if (r === "assets/css/main.css" || r === "design/tokens.json") return;
  const ext = path.extname(file);
  let src = fs.readFileSync(file, "utf8"), out = src;
  const canvas = /getContext\(/.test(src);
  const legacyHtml = ext === ".html";
  const tokenRegion = r === GLOBALS ? [src.indexOf(START), src.indexOf(END)] : null;

  const re = ext === ".css" ? [HEX, HEX3] : [HEX];
  for (const rx of re) {
    out = out.replace(rx, (m, _h, off) => {
      if (tokenRegion && off >= tokenRegion[0] && off <= tokenRegion[1]) return m;
      const lineStart = out.lastIndexOf("\n", off) + 1;
      const line = out.slice(lineStart, out.indexOf("\n", off) < 0 ? undefined : out.indexOf("\n", off));
      if (/^\s*--[\w-]+\s*:/.test(line)) return m;            // a token definition, leave
      const hex = norm(m);
      const before = out.slice(Math.max(0, off - 24), off);
      const isText = /(?<![-\w])color["']?\s*:\s*["']?$/.test(before);
      const flip = (n) => (isText && (n === "navy" || n === "navy-soft") ? "graphite" : n); // navy text vanishes on the dark theme
      const name0 = byHex.get(hex);
      const name = name0 ? flip(name0) : name0;
      const ref = `var(--${P}-${name})`;
      if (name) {
        if (canvas || legacyHtml) { report.skipped.push(`${r}: ${m} → ${name} (${canvas ? "canvas file" : "legacy HTML"})`); return m; }
        report.exact.push(`${r}: ${m} → ${ref}`); return ref;
      }
      const n = nearest(hex);
      if (legacyHtml) { report.legacy.push(`${r}: ${m} (nearest ${n.name}, distance ${n.d.toFixed(0)})`); return m; }
      if (n.d <= 18 && !canvas && !legacyHtml) {
        report.near.push(`${r}: ${m} ≈ ${n.name} (distance ${n.d.toFixed(1)})`);
        return NEAR ? `var(--${P}-${flip(n.name)})` : m;
      }
      report.off.push(`${r}: ${m} — nearest token "${n.name}" ${n.hex} (distance ${n.d.toFixed(0)}). Add a token or choose one.`);
      return m;
    });
  }
  if (ext === ".tsx" || ext === ".html") {
    for (const [from, to] of Object.entries(tokens.tailwindMap)) {
      const rx = new RegExp(`(?<![\\w-:])${from.replace(/[-/]/g, "\\$&")}(?![\\w-/])`, "g");
      out = out.replace(rx, () => { report.tw.push(`${r}: ${from} → ${to}`); return legacyHtml ? from : to; });
    }
    const leftovers = out.match(/(?<![\w-])(?:bg|text|border|ring|from|to)-(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|pink|rose)-\d{2,3}/g);
    if (leftovers && !legacyHtml) for (const l of new Set(leftovers)) report.off.push(`${r}: Tailwind "${l}" has no mapping in tokens.tailwindMap`);
    const inl = (out.match(/style=\{\{[^}]*(?:color|background|border)[^}]*\}\}/g) || []).length;
    if (inl) report.inline.push(`${r}: ${inl} inline style(s) with colors`);
  }
  if (out !== src) changes.set(file, out);
}
files.forEach(scan);

// token sync is applied to globals.css after scanning so both edits compose
const sync = syncTokens();
const globalsPath = path.join(ROOT, GLOBALS);
const scannedGlobals = changes.get(globalsPath);
if (sync.after !== sync.before) {
  if (scannedGlobals) {
    // re-run token sync on top of the scanned text
    const tmp = scannedGlobals;
    const block = tokenBlock();
    const merged = tmp.includes(START) ? tmp.replace(new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[\\s\\S]*?" + END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")), () => block) : sync.after;
    changes.set(globalsPath, merged);
  } else changes.set(globalsPath, sync.after);
}

// ---------- 5. legacy bridge ----------
const bridge = `/* GENERATED by scripts/unify-design.mjs — maps the legacy static pages onto the AADALA tokens. Load AFTER main.css. */\n:root {\n${Object.entries(tokens.legacyBridge).map(([k, v]) => `  ${k}: var(--${P}-${v}, ${tokens.colors[v].light});`).join("\n")}\n}\n[data-theme="dark"] {\n  color-scheme: dark;\n}\n`;
const bridgePath = path.join(ROOT, "assets/css/legacy-bridge.css");
const bridgeChanged = !fs.existsSync(bridgePath) || fs.readFileSync(bridgePath, "utf8") !== bridge;
const legacyLinks = [];
if (LEGACY) for (const f of files.filter((f) => f.endsWith(".html"))) {
  let s = fs.readFileSync(f, "utf8");
  if (/legacy-bridge\.css/.test(s) || !/main\.css/.test(s)) continue;
  const depth = rel(f).split("/").length - 1;
  const href = "../".repeat(depth) + "assets/css/legacy-bridge.css";
  const next = s.replace(/(<link[^>]*main\.css[^>]*>)/, `$1\n  <link rel="stylesheet" href="${href}">`);
  if (next !== s) { changes.set(f, next); legacyLinks.push(rel(f)); }
}

// ---------- output ----------
const total = report.exact.length + report.tw.length + (NEAR ? 0 : report.near.length) + (STRICT ? report.off.length : 0);
if (FIX) {
  for (const [f, c] of changes) fs.writeFileSync(f, c);
  if (bridgeChanged) fs.writeFileSync(bridgePath, bridge);
}
const sec = (t, a) => (a.length ? `## ${t} (${a.length})\n${[...new Set(a)].map((x) => "- " + x).join("\n")}\n\n` : "");
const md = `# Design unification report\n\nMode: ${FIX ? "FIX" : CHECK ? "CHECK" : "AUDIT"}${NEAR ? " +near" : ""}\n\n` +
  sec("Exact token matches (auto-fixable)", report.exact) + sec("Tailwind off-palette → design utilities (auto-fixable)", report.tw) +
  sec("Near-miss colors (--near to snap)", report.near) + sec("Off-palette colors needing a human decision", report.off) +
  sec("Legacy HTML colors (covered by the bridge CSS; migrate pages to Next.js)", report.legacy) + sec("Skipped on purpose", report.skipped) + sec("Inline color styles (move to classes)", report.inline) + sec("Legacy pages linked to bridge", legacyLinks);
fs.mkdirSync(path.join(ROOT, "design"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "design/report.md"), md);

console.log(`${FIX ? "Applied" : "Would apply"}: ${report.exact.length} color refs, ${report.tw.length} Tailwind swaps, ${report.near.length} near-miss${NEAR && FIX ? " (snapped)" : ""}.`);
console.log(`Needs a decision: ${report.off.length} off-palette, ${report.inline.length} file(s) with inline color styles.`);
const drift = sync.after !== sync.before || bridgeChanged;
console.log(`Token block + legacy bridge: ${drift ? (FIX ? "updated" : "out of sync (run design:fix)") : "in sync"}. Report: design/report.md`);
if (CHECK && (total > 0 || drift)) { console.error("design:check FAILED — run `npm run design:fix`."); process.exit(1); }
