export function normalizeArabic(value: string): string {
  return value
    .replace(/[\u064B-\u065F\u0670\u0640]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .toLowerCase();
}

export function matchDoor(query: string): Door | null {
  const haystack = normalizeArabic(query);
  let best: Door | null = null;
  let bestScore = 0;
  for (const door of DOORS) {
    let score = 0;
    for (const word of door.keywords.split(/\s+/)) {
      if (word.length > 2 && haystack.includes(normalizeArabic(word))) score += 1;
    }
    if (score > bestScore) {
      bestScore = score;
      best = door;
    }
  }
  return best;
}
